/**
 * Read masks for I/O registers, indexed by low byte of the address (0xFF00-0xFF7F).
 *
 * Unimplemented bits of an implemented register read back as 1, and entirely unmapped
 * registers read as 0xFF. This is not cosmetic: Mooneye's `bits/unused_hwio` and
 * `boot_hwio` check every one of them, and software does use them to detect hardware.
 *
 * The mask is OR'd into whatever the register itself supplies.
 */
export const IO_READ_MASK = new Uint8Array(0x80).fill(0xff);

const implemented: Record<number, number> = {
  0x00: 0xc0, // P1/JOYP — bits 6-7 unused
  0x01: 0x00, // SB — fully readable
  0x02: 0x7e, // SC — bits 1-6 unused on DMG
  0x04: 0x00, // DIV
  0x05: 0x00, // TIMA
  0x06: 0x00, // TMA
  0x07: 0xf8, // TAC — bits 3-7 unused
  0x0f: 0xe0, // IF — bits 5-7 read as 1

  // Audio. The APU arrives in Phase 07; the masks are hardware and belong here now.
  0x10: 0x80,
  0x11: 0x3f,
  0x12: 0x00,
  0x13: 0xff,
  0x14: 0xbf,
  0x16: 0x3f,
  0x17: 0x00,
  0x18: 0xff,
  0x19: 0xbf,
  0x1a: 0x7f,
  0x1b: 0xff,
  0x1c: 0x9f,
  0x1d: 0xff,
  0x1e: 0xbf,
  0x20: 0xff,
  0x21: 0x00,
  0x22: 0x00,
  0x23: 0xbf,
  0x24: 0x00,
  0x25: 0x00,
  0x26: 0x70,

  // CGB. On a DMG these are unmapped and the Mmu returns 0xFF regardless.
  0x4d: 0x7e,
  0x4f: 0xfe,
  0x51: 0xff,
  0x52: 0xff,
  0x53: 0xff,
  0x54: 0xff,
  0x55: 0x00,
  0x68: 0x00,
  0x69: 0x00,
  0x6a: 0x00,
  0x6b: 0x00,
  0x70: 0xf8,

  // LCD
  0x40: 0x00,
  0x41: 0x80,
  0x42: 0x00,
  0x43: 0x00,
  0x44: 0x00,
  0x45: 0x00,
  0x46: 0x00,
  0x47: 0x00,
  0x48: 0x00,
  0x49: 0x00,
  0x4a: 0x00,
  0x4b: 0x00,
};

for (const [offset, mask] of Object.entries(implemented)) {
  IO_READ_MASK[Number(offset)] = mask;
}

// Wave RAM is plain storage.
for (let offset = 0x30; offset <= 0x3f; offset++) IO_READ_MASK[offset] = 0x00;

